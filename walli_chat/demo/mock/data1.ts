export function getMessages() {
  const message: MarkdownChatSeed[] = [];
  for (let i = 0; i < TOTAL_MESSAGE_LENGTH; i++) {
    message.push(BASE_MESSAGE_SPECS[i % BASE_MESSAGE_SPECS.length]!);
  }
  return message;
}
